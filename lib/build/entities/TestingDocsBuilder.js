import path from "node:path";

import { PATHS } from "../config.js";
import { readFeatureRules } from "../utils/feature-files.js";
import { writeFile } from "../utils/write-file.js";
import { KEYWORDS, readStepDefinitions } from "../utils/step-definitions.js";

/*
  Writes the testing docs into dist/_assets:

    README.md                         an index of the success criteria the scenarios cover
    available-steps.md                every step a scenario can use, by keyword and file
    recommendations.md                the scenarios that test our own recommendations
    success-criteria/<sc>-<name>.md   the steps to use, an example scenario and the
                                      components already tested, for one criterion

  Everything is derived from the feature files and step definitions in src/,
  so the docs are regenerated on every build and can't fall behind the tests.
*/

const GENERATED_NOTE = "Generated by `npm run build` from the feature files in `src/components/` and the step definitions in `src/tests/_shared-steps/`. Edit those, not this file.";
const UNDERSTANDING_URL = "https://www.w3.org/WAI/WCAG22/Understanding/";
const CRITERIA_DIR = "success-criteria";

const slugify = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// Path from a generated file's folder to a source file, with forward slashes for Markdown
const linkFrom = (fromDir, toPath) => path.relative(fromDir, toPath).split(path.sep).join("/");

// Sort "1.4.3" before "1.4.10"
const compareCriteria = (a, b) => {
  const [x, y] = [a, b].map(sc => sc.split(".").map(Number));
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
};

const describeTypes = (types) => {
  if (types.has("automatic") && types.has("manual")) return "Automatic and manual";
  if (types.has("manual")) return "Manual";
  return "Automatic";
};

export class TestingDocsBuilder {
  #definitions = null;
  #rules = null;

  async build () {
    this.#definitions = readStepDefinitions();
    this.#rules = readFeatureRules();

    const criteria = this.#collectCriteria();
    const recommendations = this.#collectRecommendations();

    await Promise.all([
      writeFile(path.join(PATHS.ASSETS_DIST, "README.md"), this.#renderIndex(criteria)),
      writeFile(path.join(PATHS.ASSETS_DIST, "available-steps.md"), this.#renderAvailableSteps()),
      writeFile(path.join(PATHS.ASSETS_DIST, "recommendations.md"), this.#renderRecommendations(recommendations)),
      ...criteria.map(criterion => writeFile(
        path.join(PATHS.ASSETS_DIST, CRITERIA_DIR, `${criterion.slug}.md`),
        this.#renderCriterion(criterion)
      ))
    ]);
  }

  // The definition a feature file step runs, or null if there isn't one.
  // Cucumber matches on the text alone, so an assertion written as "And"
  // under a "When" still runs; the same-keyword definition is preferred so
  // the step is listed under the right heading
  #definitionFor (step) {
    return this.#definitions.find(definition => definition.matches(step.text, step.keyword)) ??
      this.#definitions.find(definition => definition.matches(step.text)) ??
      null;
  }

  // Fold one Rule's steps and usage into a group (a success criterion, or the recommendations)
  #addRule (group, rule) {
    if (rule.type) group.types.add(rule.type);
    for (const scenario of rule.scenarios) {
      for (const step of scenario.steps) {
        const definition = this.#definitionFor(step);
        if (definition) {
          group.definitions.add(definition);
        } else {
          console.warn(`No step definition matches "${step.keyword} ${step.text}" (${rule.featurePath}:${step.line})`);
          group.unmatched.add(`${step.keyword} ${step.text}`);
        }
      }
    }
    const usage = group.usage.get(rule.component.slug) ?? { component: rule.component, files: new Map() };
    usage.files.set(rule.featureFile, rule.featurePath);
    group.usage.set(rule.component.slug, usage);
    group.example ??= rule.example;
  }

  #newGroup (fields) {
    return { types: new Set(), definitions: new Set(), unmatched: new Set(), usage: new Map(), example: null, ...fields };
  }

  #collectCriteria () {
    const criteria = new Map();
    for (const rule of this.#rules.filter(rule => rule.sc)) {
      if (!criteria.has(rule.sc)) {
        criteria.set(rule.sc, this.#newGroup({
          sc: rule.sc,
          name: rule.name,
          level: rule.level,
          slug: `${rule.sc}-${slugify(rule.name)}`
        }));
      }
      this.#addRule(criteria.get(rule.sc), rule);
    }
    return [...criteria.values()].sort((a, b) => compareCriteria(a.sc, b.sc));
  }

  #collectRecommendations () {
    const group = this.#newGroup({ scenarios: [] });
    for (const rule of this.#rules.filter(rule => rule.recommendation)) {
      this.#addRule(group, rule);
      for (const scenario of rule.scenarios) {
        group.scenarios.push({ component: rule.component, featureFile: rule.featureFile, featurePath: rule.featurePath, name: scenario.name });
      }
    }
    return group;
  }

  // A step as a linked list item, with its description if it has one
  #renderStep (definition, fromDir) {
    const note = definition.description ? ` — ${definition.description}` : "";
    return `- [\`${definition.keyword} ${definition.text}\`](${linkFrom(fromDir, definition.filePath)})${note}`;
  }

  // The steps a group uses, split into the setup (Given and When) and the assertions (Then)
  #renderSteps (group, fromDir) {
    const steps = [...group.definitions];
    const setup = steps.filter(definition => definition.keyword !== "Then");
    const assertions = steps.filter(definition => definition.keyword === "Then");
    const output = [];
    if (setup.length) output.push("## Setup", "", ...setup.map(definition => this.#renderStep(definition, fromDir)), "");
    if (assertions.length) output.push("## Assertions", "", ...assertions.map(definition => this.#renderStep(definition, fromDir)), "");
    if (group.unmatched.size) {
      output.push(
        "## Steps without a definition",
        "",
        "These steps are used in a scenario but don't match any step definition, so the scenario can't run.",
        "",
        ...[...group.unmatched].map(step => `- \`${step}\``),
        ""
      );
    }
    return output;
  }

  #renderUsage (group, fromDir) {
    const output = ["## Used in", ""];
    for (const { component, files } of group.usage.values()) {
      const links = [...files].map(([file, filePath]) => `[${file}](${linkFrom(fromDir, filePath)})`);
      output.push(`- ${component.name}: ${links.join(", ")}`);
    }
    output.push("");
    return output;
  }

  #renderCriterion (criterion) {
    const fromDir = path.join(PATHS.ASSETS_DIST, CRITERIA_DIR);
    const title = `${criterion.sc} ${criterion.name}`;
    const level = criterion.level ? `Level ${criterion.level}. ` : "";
    const output = [
      `# ${title}`,
      "",
      GENERATED_NOTE,
      "",
      `${level}[Understanding ${title} on w3.org](${UNDERSTANDING_URL}${slugify(criterion.name)}.html).`,
      "",
      `Scenarios: ${describeTypes(criterion.types).toLowerCase()}.`,
      "",
      ...this.#renderSteps(criterion, fromDir)
    ];
    if (criterion.example) {
      output.push("## Example", "", "```gherkin", criterion.example, "```", "");
    }
    output.push(...this.#renderUsage(criterion, fromDir));
    return output.join("\n");
  }

  #renderRecommendations (group) {
    const fromDir = PATHS.ASSETS_DIST;
    const output = [
      "# Recommendations",
      "",
      GENERATED_NOTE,
      "",
      "Scenarios tagged `@recommendation` test our own best practice, beyond what WCAG requires. They use the same shared steps as the success criteria.",
      "",
      ...this.#renderSteps(group, fromDir),
      "## Scenarios",
      ""
    ];
    for (const scenario of group.scenarios) {
      output.push(`- ${scenario.component.name}: ${scenario.name} ([${scenario.featureFile}](${linkFrom(fromDir, scenario.featurePath)}))`);
    }
    output.push("");
    return output.join("\n");
  }

  #renderIndex (criteria) {
    const output = [
      "# Testing documentation",
      "",
      GENERATED_NOTE,
      "",
      "Every component's test scenarios are written in Gherkin from a shared set of steps, and tagged with the WCAG success criterion they test. These pages show which steps to use for each criterion, with an example scenario and the components that already test it.",
      "",
      "- [Available steps](available-steps.md): every step a scenario can use, with what it does",
      "- [Recommendations](recommendations.md): the scenarios for our own best practice, beyond WCAG",
      "",
      "## Success criteria",
      "",
      "| Success criterion | Level | Scenarios | Components |",
      "| --- | --- | --- | --- |"
    ];
    for (const criterion of criteria) {
      const components = [...criterion.usage.values()].map(({ component }) => component.name).join(", ");
      output.push(`| [${criterion.sc} ${criterion.name}](${CRITERIA_DIR}/${criterion.slug}.md) | ${criterion.level ?? ""} | ${describeTypes(criterion.types)} | ${components} |`);
    }
    output.push("");
    return output.join("\n");
  }

  #renderAvailableSteps () {
    const fromDir = PATHS.ASSETS_DIST;
    const output = [
      "# Available steps",
      "",
      GENERATED_NOTE,
      "",
      "Every step a scenario can use, grouped by keyword and then by the file the step definition lives in. Reuse these before adding a new step.",
      ""
    ];
    for (const keyword of KEYWORDS) {
      const steps = this.#definitions.filter(definition => definition.keyword === keyword);
      if (!steps.length) continue;
      output.push(`## ${keyword}`, "");
      // One section per file, in file order
      const groups = [...new Set(steps.map(step => step.group))];
      for (const group of groups) {
        output.push(`### ${group}`, "");
        output.push(...steps.filter(step => step.group === group).map(step => this.#renderStep(step, fromDir)));
        output.push("");
      }
    }
    return output.join("\n");
  }
}
